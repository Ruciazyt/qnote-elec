/**
 * 分割线（拖拽热区）的厚度
 *
 * 它作为 flex 兄弟节点真实占位，所以旁边的内容区会被压缩这么多 —— 这是有意的：
 * 分割线做成 flex 子节点（而不是 absolute 叠在侧栏左边缘），
 * 才能保证它**完全**落在 DOM 区域内。
 *
 * 这一点很关键：网页由主进程 WebContentsView 承载，是盖在 DOM 之上的原生层，
 * 压在它上面的 DOM 是收不到鼠标事件的。分割线只要有哪怕 1px 伸进网页区，
 * 那部分就点不动了。放成 flex 子节点则彻底避开这个问题。
 */
export const PANEL_RESIZER_WIDTH = 7;

/**
 * 折叠态侧栏的几何规则
 *
 * 笔记页、题单页、快捷方式面板、应用管理页共用这一套数 —— 折叠后
 * 它们都是同一种东西：一条窄轨道，轨道里放一个切换按钮。
 *
 * 这套数解决三件事：
 *
 * 1. 折叠轨里按钮**左右留白相等**（≥4px），focus 描边不会被轨道裁掉；
 * 2. 折叠↔展开切换时按钮**横向零位移** —— 同一个按钮落在同一个 x 上，
 *    面板在它旁边变宽变窄，按钮自己不动；
 * 3. 四个页面的折叠轨道是**同一套几何**，不再各写各的 40 / 44。
 *
 * ## 数字怎么来的
 *
 *   轨道外宽 48px，折叠态的分隔线用 inset 阴影画 —— 阴影画在盒内、不占布局，
 *   所以内容盒就是完整的 48px（早期用真 border-r 时内容盒只有 47px，那一版已改掉）。
 *   折叠按钮 32×32，固定锚在轨道左起 8px
 *   → 8 + 32 + 8 = 48，按钮正好落在轨道正中，左右各留 8px
 *   → focus 描边向外扩 1px 之后还剩 7px 余量，四边完整可见
 *
 *   展开态头部左内边距同样取 8px（PANEL_HEADER_PADDING_X），
 *   于是两态里按钮都落在 8..40，切换时横向零位移。
 *
 * ## 两个必须避开的坑
 *
 * - 折叠态按钮的位置要有**确定的锚点**，别让它跟着内容盒宽度漂：
 *   左锚的三页（笔记 / 题单 / 应用管理）用固定左内边距
 *   （PANEL_COLLAPSED_BUTTON_INSET = 8），它跟分隔线用什么画法无关；
 *   右锚的快捷方式面板现在也是**固定锚定** —— 固定右内边距
 *   （同一个 PANEL_COLLAPSED_BUTTON_INSET = 8）+ justify-end，不再用居中。
 *   居中在「分隔线不占内容盒」时恰好也是 8px、看着等价，但它把按钮位置
 *   绑在这个前提上：分隔线一旦改回真边框（内容盒 47px），居中就变成 7.5px
 *   的小数偏移、左右留白变成 7.5 / 8.5；而且宽度过渡期间轨道还是宽的，
 *   居中会把按钮摆到轨道中线而不是钉在锚点上。固定锚定才两种情况都稳。
 * - 折叠态的 **gap 必须是 0**：标题与操作区虽然宽度归零（w-0），gap 照样占位，
 *   会把按钮整体往左挤 —— 这正是「按钮贴住轨道左缘、focus 描边左侧被裁掉」的成因。
 *
 * ## 内容列的左内边距：约定 8px，写法是 px-2
 *
 * 笔记页、题单页、应用管理页这三页，内容列的左内边距取 8px，
 * 与头部按钮的左缘对齐 —— 头部按钮落在 8..40，内容列的内容也从 8 开始。
 * 写法统一用 Tailwind 的 `px-2`（0.5rem = 8px），**不**走行内样式引用
 * PANEL_HEADER_PADDING_X。
 *
 * 为什么不绑成同一个常量：两者的物理含义不同 —— 头部那个 8px 是
 * 「按钮在轨道里的锚点」，内容列那个 8px 是「内容不要贴住轨道」。
 * 两者数值相等是当前几何（48 = 2×8 + 32）带来的结果，不是同一个参数。
 * 真要全局跟随，那是跨页改动：四页各归一个 Bot，得一起动，由架构师统一派工，
 * 别在单页里自作主张改另外三页。
 *
 * 另外，快捷方式面板不在这条关系里 —— 它是贴在窗口右缘的竖轨，
 * 按钮从右缘往左锚定，没有「内容列与头部按钮共左缘」这回事。
 *
 * 护栏：layout.test.ts 里那条「当前几何规格：轨道 48、按钮 32、内缩 8」
 * 用字面量锁死了这几个数 —— 谁改了 PANEL_HEADER_PADDING_X，测试先红，
 * 强制一次四页巡检，不会有「改了一页忘了另外三页」的静默漂移。
 */
export const PANEL_COLLAPSED_WIDTH = 48;

/** 折叠态切换按钮的边长（方形按钮） */
export const PANEL_COLLAPSED_BUTTON_SIZE = 32;

/**
 * 折叠态按钮距轨道左缘的距离（固定锚点）
 *
 * 与 PANEL_HEADER_PADDING_X 必须相等 —— 两态共用同一个左缘，
 * 按钮切换时才会横向零位移。
 */
export const PANEL_COLLAPSED_BUTTON_INSET = 8;

/**
 * 展开态面板头部的左右内边距
 *
 * 取值与 PANEL_COLLAPSED_BUTTON_INSET 相同（8px）：折叠态按钮左缘 8px、
 * 展开态按钮左缘 8px，切换时按钮不横移。头部标题与操作区跟在按钮后面，
 * 按钮与标题同处一行、同一条基线。
 */
export const PANEL_HEADER_PADDING_X = 8;

/**
 * 折叠轨里竖排标签按钮的内缩（左右各一次 + 下边一次）
 *
 * 这个按钮是折叠轨上的**第二个**可聚焦控件（第一个是顶部的展开箭头）。
 * 它贴着窗口右缘，焦点指示向外扩 1px 会超出视口，焦点框就缺一条右边；
 * 不留底边距的话，往下那 1px 会落到轨道外面被裁掉，焦点框缺一条底边。
 *
 * ## 数字怎么来的
 *
 *   轨宽 48px（PANEL_COLLAPSED_WIDTH），左右各内缩 4px、底部再内缩 4px
 *   → 按钮盒横向落在 4..44（宽 40px）
 *   → 焦点指示向外扩 1px 后落在 3..45，离左右边缘各余 3px，四边完整可见
 *
 * ## 这 3px 是按几 px 的指示算的（改 focus ring 前先回来核这里）
 *
 * 折叠轨上有两个可聚焦控件，**描边来源不一样**，别混：
 *
 * - 顶部那个展开箭头走 ui/button 的 `<Button>`，吃基类的 ring。
 *   按钮盒落在 8..40、轨宽 48，基类 `focus-visible:ring-1` 时描边外扩 1px
 *   → 落在 7..41，离轨边各余 **7px**；基类改成 ring-2 后外扩 2px
 *   → 落在 6..42，余 **6px**，仍不会被裁。
 * - 这个竖排标签按钮是**原生 <button>**，不是 ui/button 的 Button ——
 *   它身上**没有** focus-visible:ring 类（实测 box-shadow: none），
 *   焦点指示是浏览器默认 outline（Chromium 约 1px）。
 *   4px 内缩 + 描边外扩 1px → 落在 3..45，离左右边缘各余 **3px**，底边同理。
 *   **基类 ring 怎么改都影响不到它** —— 它不吃 ring，余量恒为 3px。
 *
 * 「ring 加粗到 2px，这里余量就降到 2px」这个说法在本仓库里**没有实际发生的地方**：
 * 那条结论成立的条件是「ring 变 2px，且按钮距 overflow-hidden 容器边缘不足 2px」，
 * 而贴边的按钮都够 —— 箭头离轨边 8px，竖排标签离轨边 4px。
 *
 * **ring-2 是上限，不要再往上粗**：ring-3 时箭头那处余量降到 5px；
 * 竖排标签哪天若被补上 ring（它现在没有），4px 内缩 − 3px 只剩 1px，
 * 描边几乎贴住视口边缘。基类 ring 粗细是全局决定，架构师已定案 ring-2。
 *
 * 描边粗细改之前先量这一处的余量。
 */
export const PANEL_RAIL_LABEL_INSET = 4;

/** 把宽度钳制到可用区间 */
export function clampPanelWidth(
  width: number,
  min: number,
  max: number
): number {
  return Math.min(Math.max(Math.round(width), min), Math.max(min, max));
}
